def folder_with_recordings():
    """Where to start looking: real recordings, then the synthetic set, then nowhere.

    A fresh clone has neither, since both are excluded from the repository. That is the
    normal state, and the app opens asking for a folder rather than complaining.
    """
    for candidate in (DEFAULT_DATA, DEMO_DATA):
        if candidate.exists() and any(candidate.rglob("*.csv")):
            return candidate
    return None


