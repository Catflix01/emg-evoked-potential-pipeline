CHOOSE_FOLDER_ON_WINDOWS = '''
Add-Type -AssemblyName System.Windows.Forms
$chooser = New-Object System.Windows.Forms.FolderBrowserDialog
$chooser.Description = "Choose the folder holding your recordings"
if ($chooser.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {
    Write-Output $chooser.SelectedPath
}
'''


def folder_chooser_command():
    """The command that opens this computer's folder chooser, or None if it has none.

    Each system already ships one, so nothing has to be installed for this to work.
    """
    if sys.platform == "darwin":
        return ["osascript", "-e", CHOOSE_FOLDER_ON_MAC]
    if os.name == "nt":
        return ["powershell", "-NoProfile", "-STA", "-Command", CHOOSE_FOLDER_ON_WINDOWS]
    return None


def pick_folder():
    """Open the folder chooser and return what was picked, or None.

    The chooser runs as a separate program rather than inside this one. A dialog has to
    own its program's main thread, and this app's main thread is busy serving the page,
    so opening one here freezes the app instead of showing a window.

    Clicking Cancel is not a problem, so it says nothing and changes nothing.
    """
    command = folder_chooser_command()
    if command is None:
        return pick_folder_the_old_way()

    quietly = {"creationflags": subprocess.CREATE_NO_WINDOW} if os.name == "nt" else {}
    try:
        # generous, but bounded: someone who walks away should not wedge the app
        finished = subprocess.run(command, capture_output=True, text=True,
                                  timeout=300, **quietly)
    except subprocess.TimeoutExpired:
        st.warning("The folder window was left open too long. Click Browse again, or "
                   "paste the folder in the box below.", icon="📂")
        return None
    except OSError as e:
        st.warning(f"The folder chooser would not open ({e}). Type or paste the folder "
                   "in the box below instead.", icon="📂")
        return None

    return finished.stdout.strip().splitlines()[0] if finished.stdout.strip() else None


def pick_folder_the_old_way():
    """For systems with no chooser of their own, such as Linux.

    In-process, so it carries the freezing problem described above. It stays only
    because the alternative on those systems is no button at all.
    """
    try:
        import tkinter as tk
        from tkinter import filedialog
    except ImportError:
        st.warning("This copy of the app was built without a folder chooser. Type or "
                   "paste the folder in the box below instead.", icon="📂")
        return None

    try:
        chooser = tk.Tk()
        chooser.withdraw()
        chooser.attributes("-topmost", True)   # otherwise it opens behind the browser
        chosen = filedialog.askdirectory(title="Choose the folder holding your recordings")
        chooser.destroy()
        return chosen or None
    except Exception as e:
        st.warning(f"The folder chooser would not open ({e}). Type or paste the folder "
                   "in the box below instead.", icon="📂")
        return None


@st.cache_data(show_spinner=False)
def which_copy_is_this():
    """Which build this is, so a stale copy cannot pass for a current one.

    A copy left running keeps serving the code it was built with, and looks identical to
    one built this minute. Saying so on screen is the difference between "the app is
    broken" and "this is an old copy".
    """
    stamped = ROOT / "build-info.txt"
    if stamped.exists():
        return stamped.read_text().strip()
    try:
        commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                                capture_output=True, text=True, timeout=5).stdout.strip()
    except Exception:
        commit = ""
    return f"running from source, {commit}" if commit else "running from source"


@st.cache_data(show_spinner=False)
def recordings_in(folder):
    """The recordings under a folder, or none if it does not exist yet."""
    path = Path(folder).expanduser() if folder.strip() else None
    return find_recordings(path) if path and path.exists() else []


@st.cache_data(show_spinner="Reading a few recordings to see which channel list fits…")
def which_lineups_fit(folder):
    """Cached on the folder, so it reads the files once rather than on every click."""
    return lineups.that_fit(recordings_in(folder), config)


@st.cache_data(show_spinner=False)
def load_manifest(path, sheet):
    """Read the channel lineup workbook. Cached so it isn't re-read on every click."""
    return pd.read_excel(path, sheet_name=sheet)


def build_report(folder, manifest, settings, lineup=None):
    """The same self-check the command-line tool prints, as one block of text."""
    recordings = find_recordings(folder)
    has_sessions = any(selfcheck.session_from_path(r)["experiment"] is not None
                       for r in recordings)
    lines = [f"EMG PIPELINE SELF-CHECK", f"  {len(recordings)} recordings under {folder}"]
    lines += selfcheck.check_folders(recordings)
    lines += selfcheck.check_protocol_folders(recordings, has_sessions)
    lines += selfcheck.check_recordings(recordings, manifest, settings, lineup)[0]
    lines += [selfcheck.heading("PROVISIONAL COLUMNS"),
              "  These have never been checked against data known to be correct:",
              "    " + ", ".join(selfcheck.PROVISIONAL)]
    return "\n".join(lines)


